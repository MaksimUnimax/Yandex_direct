def rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def clean(value: str) -> str:
    return " ".join(str(value or "").replace("|", ";").split())


def compact_link(url: str) -> str:
    url = clean(url)
    if not url or url == "Не требуется":
        return "—"
    parsed = urlsplit(url)
    label = parsed.path or "/"
    if parsed.query:
        label += "?" + parsed.query
    return f"[{label}]({url})"


def compact_links(value: str) -> str:
    result = [compact_link(item) for item in clean(value).split(";") if item]
    return "<br>".join(result) if result else "—"


def representative_by_unit() -> dict[str, str]:
    demand = {clean(r["phrase"]).casefold(): int(r["max_result_count"]) for r in rows(DEMAND_AUTHORITY)}
    members: dict[str, list[tuple[int, str]]] = {}
    for row in rows(SEMANTIC_AUTHORITY):
        unit = row["final_structural_unit_id"]
        if unit and row["final_semantic_state"] in {"ASSIGNED", "ASSIGNED_HOLD"}:
            phrase = clean(row["phrase"])
            members.setdefault(unit, []).append((demand.get(phrase.casefold(), 0), phrase))
    return {unit: sorted(values, key=lambda item: (-item[0], item[1].casefold()))[0][1] for unit, values in members.items()}


def build() -> str:
    routes = rows(ROUTE_AUTHORITY)
    links = rows(LINK_AUTHORITY)
    assert len(routes) == 46
    assert len(links) == 15
    reps = representative_by_unit()

    out = [PREFIX]
    for i, route in enumerate(routes, 1):
        topic = reps.get(route["structural_unit_id"], "Тема")
        primary = compact_link(route["final_primary_page"])
        supporting = compact_links(route["final_supporting_pages"])
        out.append(f"| {i} | {topic} | {primary} | {supporting} |")

    out.append("\n" + SUFFIX_CHECKS)

    seen: set[tuple[str, str]] = set()
    visible = []
    for link in links:
        pair = (clean(link["source_url"]), clean(link["target_url"]))
        if pair in seen:
            continue
        seen.add(pair)
        visible.append(pair)
    assert len(visible) == 14
    for i, (source, target) in enumerate(visible, 1):
        out.append(f"| {i} | {compact_link(source)} | {compact_link(target)} |")

    out.append("\n" + TAIL)
    for i, (title, publisher, url) in enumerate(BIBLIOGRAPHY, 1):
        out.append(f"{i}. «{title}» — {publisher}. {url}")
    return "\n".join(out).strip() + "\n"


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    text = build()
    # Hard stop if old client-language failure classes reappear.
    banned = [
        "не выдавать за готовую", "получить названное доказательство", "из них не следует",
        "не внедрять", "не размещать", "что сейчас запрещено", "граница приёмки сейчас",
        "отдельно санкционировать", "новые факты не собирались", "post-hoc",
        "Откройте страницу", "Найдите на странице", "Перейдите по ссылке",
    ]
    hits = [x for x in banned if x.casefold() in text.casefold()]
    if hits:
        raise SystemExit(f"CLIENT_LANGUAGE_GATE_FAIL: {hits}")
    OUTPUT.write_text(text, encoding="utf-8")
    print(OUTPUT)

if __name__ == "__main__":
    main()
