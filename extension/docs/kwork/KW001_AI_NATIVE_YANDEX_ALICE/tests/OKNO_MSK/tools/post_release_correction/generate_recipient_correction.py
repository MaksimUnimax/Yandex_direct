def md(value: object) -> str:
    return str(value or "").replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()


def short_list(value: str, limit: int = 12) -> str:
    parts = [p.strip() for p in str(value or "").split("|") if p.strip()]
    if not parts:
        return "Нет отдельного набора фраз: действие относится к пакету или объекту."
    shown = parts[:limit]
    tail = f"; ещё {len(parts) - limit}" if len(parts) > limit else ""
    return "; ".join(shown) + tail


