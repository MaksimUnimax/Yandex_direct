def repeat_table_headers():
    doc = Document(DOCX)
    for table in doc.tables:
        if not table.rows:
            continue
        trPr = table.rows[0]._tr.get_or_add_trPr()
        existing = trPr.find(qn('w:tblHeader'))
        if existing is None:
            hdr = OxmlElement('w:tblHeader')
            hdr.set(qn('w:val'), 'true')
            trPr.append(hdr)
    doc.save(DOCX)


